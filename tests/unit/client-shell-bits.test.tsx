// @vitest-environment happy-dom
import { createRoot, type Root } from 'hono/jsx/dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Excerpt } from '../../linkedin-dashboard/src/client/components/Facts.tsx';
import { InlineError } from '../../linkedin-dashboard/src/client/components/Feedback.tsx';
import { ResourceView } from '../../linkedin-dashboard/src/client/components/Screen.tsx';
import { SplitView } from '../../linkedin-dashboard/src/client/components/SplitView.tsx';
import { Tag } from '../../linkedin-dashboard/src/client/components/Status.tsx';
import { ApiError } from '../../linkedin-dashboard/src/client/lib/api.ts';
import { useMutation } from '../../linkedin-dashboard/src/client/lib/store.ts';
import { selectId, useSelectedId } from '../../linkedin-dashboard/src/client/lib/router.ts';
import { flush } from '../helpers/clientHarness.ts';

// The shell pieces that only appear in a state the happy path never reaches: a
// narrow window, a failed request that is not an API refusal, a selection
// carried in the URL, and text the product is asserting is its own.

let container: HTMLElement;
let root: Root | null = null;

beforeEach(() => {
  document.body.innerHTML = '<div id="mount"></div>';
  container = document.getElementById('mount') as HTMLElement;
});

afterEach(() => {
  root?.unmount();
  root = null;
  document.body.innerHTML = '';
  location.hash = '';
  vi.restoreAllMocks();
  vi.unstubAllGlobals();
});

async function render(node: unknown): Promise<void> {
  root = createRoot(container);
  root.render(node as never);
  await flush(10);
}

/** Answers every media query the same way, so the layout branch is a choice. */
function stubViewport(matches: boolean): void {
  vi.stubGlobal('matchMedia', (query: string) => ({
    matches,
    media: query,
    onchange: null,
    addEventListener: () => {},
    removeEventListener: () => {},
    addListener: () => {},
    removeListener: () => {},
    dispatchEvent: () => false,
  }));
}

const text = () => container.textContent ?? '';

describe('a tag next to a status chip', () => {
  it('renders as a word, not as a domain state', async () => {
    await render(<Tag>local-write</Tag>);

    const tag = container.querySelector('.chip');
    // A chip with a glyph means "this record is in this state". A blocker name
    // or a permission tier is not a state, and dressing it as one drains the
    // meaning out of the ones that are.
    expect(tag?.className).toContain('chip--tag');
    expect(tag?.querySelector('[aria-hidden="true"]')).toBeNull();
    expect(text()).toBe('local-write');
  });
});

describe('an excerpt the product wrote itself', () => {
  it('sheds the untrusted envelope only when the caller says so', async () => {
    await render(<Excerpt text="Generated by this tool." untrusted={false} />);

    expect(container.querySelector('pre')?.getAttribute('data-untrusted')).toBeNull();
  });

  it('carries the envelope by default, because forgetting must fail safe', async () => {
    await render(<Excerpt text="Text read out of a member's file." />);

    // An omitted prop is far likelier to be an oversight than a claim that the
    // text is ours.
    expect(container.querySelector('pre')?.getAttribute('data-untrusted')).toBe('true');
  });
});

describe('a refusal shown inline', () => {
  it('names the blockers and says when it is worth trying again', async () => {
    await render(
      <InlineError
        error={
          new ApiError(503, {
            code: 'CAPABILITY_UNAVAILABLE',
            message: 'LinkedIn did not answer',
            blockers: ['probe_unreachable'],
            retryable: true,
          })
        }
      />,
    );

    // Retryable is the difference between "wait and press it again" and "go and
    // fix something", and the member cannot tell those apart from the message.
    expect(text()).toContain('probe_unreachable');
    expect(text()).toMatch(/worth retrying/i);
  });

  it('says nothing about retrying when it is not worth it', async () => {
    await render(
      <InlineError
        error={new ApiError(400, { code: 'INVALID_INPUT', message: 'that is not a lane' })}
      />,
    );

    expect(text()).not.toMatch(/worth retrying/i);
  });
});

describe('a resource that failed to load', () => {
  it('offers a way to try again when the caller can reload it', async () => {
    let reloads = 0;
    await render(
      <ResourceView
        resource={{
          status: 'error',
          data: null,
          error: new ApiError(500, { code: 'INTERNAL', message: 'the read failed' }),
        }}
        reload={() => {
          reloads += 1;
        }}
        label="claims"
      >
        {() => <p>never rendered</p>}
      </ResourceView>,
    );

    const retry = Array.from(container.querySelectorAll('button')).find((b) =>
      /try again/i.test(b.textContent ?? ''),
    );
    expect(retry).toBeTruthy();
    retry?.click();
    await flush(8);
    expect(reloads).toBe(1);
  });
});

describe('a resource that failed with no way to reload it', () => {
  it('shows the refusal and offers no button that would do nothing', async () => {
    await render(
      <ResourceView
        resource={{
          status: 'error',
          data: null,
          error: new ApiError(403, { code: 'FORBIDDEN', message: 'this view is switched off' }),
        }}
        label="claims"
      >
        {() => <p>never rendered</p>}
      </ResourceView>,
    );

    // A "Try again" that cannot try again is worse than no button: it teaches
    // the member that the control does nothing.
    expect(text()).toContain('this view is switched off');
    expect(
      Array.from(container.querySelectorAll('button')).some((b) =>
        /try again/i.test(b.textContent ?? ''),
      ),
    ).toBe(false);
  });
});

describe('the split layout on a narrow window', () => {
  it('shows the detail in a drawer rather than beside the list', async () => {
    stubViewport(true);

    await render(
      <SplitView
        list={<p>the list</p>}
        detail={<p>the detail</p>}
        detailTitle="Claim"
        selectionKey="clm_1"
        onCloseDetail={() => {}}
      />,
    );

    // Two columns in a phone-width window would leave both unreadable, so the
    // detail becomes a drawer over the list it came from.
    expect(container.querySelector('[role="dialog"]')).toBeTruthy();
    expect(text()).toContain('the detail');
  });

  it('keeps the drawer shut when nothing is selected', async () => {
    stubViewport(true);

    await render(
      <SplitView
        list={<p>the list</p>}
        detail={null}
        detailTitle="Claim"
        selectionKey={null}
        onCloseDetail={() => {}}
      />,
    );

    expect(text()).toContain('the list');
    expect(text()).not.toContain('the detail');
  });
});

describe('the selection in the URL', () => {
  function Selected() {
    const id = useSelectedId();
    return <p>{id ?? 'nothing selected'}</p>;
  }

  it('reads the id out of the fragment', async () => {
    location.hash = '#/evidence/queue?id=clm_42';

    await render(<Selected />);

    // The id travels as a query inside the fragment so it can be bookmarked and
    // shared, unlike the launch token which the client swallows.
    expect(text()).toBe('clm_42');
  });

  it('reports nothing selected on a bare route', async () => {
    location.hash = '#/evidence/queue';

    await render(<Selected />);

    expect(text()).toBe('nothing selected');
  });

  it('sets and clears the selection without the caller knowing the route', async () => {
    location.hash = '#/evidence/queue';

    selectId('clm_7');
    expect(location.hash).toContain('id=clm_7');
    expect(location.hash).toContain('/evidence/queue');

    selectId(null);
    expect(location.hash).not.toContain('id=');
  });
});

describe('a mutation that fails outside the API', () => {
  function Mutating() {
    const mutation = useMutation();
    return (
      <div>
        <button type="button" onClick={() => void mutation.run('/anything', {})}>
          run
        </button>
        <span>{mutation.error ? `${mutation.error.code}: ${mutation.error.message}` : 'idle'}</span>
      </div>
    );
  }

  it('shows the transport failure rather than swallowing it', async () => {
    vi.stubGlobal('fetch', async () => {
      throw new TypeError('Failed to fetch');
    });

    await render(<Mutating />);
    container.querySelector('button')?.click();
    await flush(12);

    // A dropped loopback connection is not a refusal from the server, and
    // reporting nothing would leave the button looking like it did the thing.
    expect(text()).toMatch(/INTERNAL/);
    expect(text()).toMatch(/failed to fetch/i);
  });
});

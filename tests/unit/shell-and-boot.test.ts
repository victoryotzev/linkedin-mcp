import { describe, expect, it } from 'vitest';
import { BOOT_FALLBACK_HEADING, renderShell } from '../../linkedin-dashboard/src/html.ts';

// The server-rendered shell.
//
// Two rules govern it, and both are load-bearing rather than stylistic. It
// carries no inline script and no inline style, which is what makes
// `script-src 'self'; style-src 'self'` possible at all. And #root ships a
// static fallback that the client's first act is to clear — so a member seeing
// it knows the bundle did not run, rather than staring at a blank page and
// concluding the product is broken in some other way.

const MANIFEST = {
  'app.js': '/assets/app.abc123.js',
  'app.css': '/assets/app.def456.css',
  'theme-boot.js': '/assets/theme-boot.789abc.js',
} as never;

describe('the shell', () => {
  it('links the built assets by their hashed names', () => {
    const html = renderShell(MANIFEST);

    expect(html).toContain('/assets/app.abc123.js');
    expect(html).toContain('/assets/app.def456.css');
    expect(html).toContain('/assets/theme-boot.789abc.js');
  });

  it('carries no inline script and no inline style', () => {
    const html = renderShell(MANIFEST);

    // This is what the CSP depends on: any inline block here would force
    // 'unsafe-inline' or a nonce, and the policy is the reason there is none.
    expect(html).not.toMatch(/<script(?![^>]*\bsrc=)[^>]*>/i);
    expect(html).not.toMatch(/<style[\s>]/i);
    expect(html).not.toMatch(/\son[a-z]+=/i);
  });

  it('loads the theme boot script before the stylesheet has painted', () => {
    const html = renderShell(MANIFEST);

    // A classic script in <head>, not a module: modules are deferred, and the
    // deferral is exactly the flash of the wrong colours this prevents.
    const head = html.slice(html.indexOf('<head>'), html.indexOf('</head>'));
    expect(head).toContain('theme-boot.789abc.js');
    expect(head).not.toMatch(/type=["']module["']/);
  });

  it('ships a fallback panel that says nothing is at risk', () => {
    const html = renderShell(MANIFEST);

    expect(html).toContain(BOOT_FALLBACK_HEADING);
    // A member looking at a dead dashboard needs to know their data is fine,
    // because the alternative reading is that something went wrong with it.
    expect(html).toMatch(/nothing has been changed/i);
    expect(html).toMatch(/no data is at risk/i);
    // And it names the files that were expected, so the failure is diagnosable.
    expect(html).toContain('/assets/app.abc123.js');
  });

  it('marks the fallback as an alert so a screen reader announces it', () => {
    expect(renderShell(MANIFEST)).toMatch(/role="alert"/);
  });

  it('declares a language and a viewport', () => {
    const html = renderShell(MANIFEST);

    expect(html).toMatch(/<html lang="en">/);
    expect(html).toMatch(/name="viewport"/);
  });
});

describe('escaping', () => {
  it('escapes an asset path that carries markup characters', () => {
    const html = renderShell({
      'app.js': '/assets/<script>alert(1)</script>.js',
      'app.css': '/assets/"onload="alert(2).css',
      'theme-boot.js': "/assets/'&.js",
    } as never);

    // The manifest is generated by the build rather than by a user, but the
    // shell is the last thing between it and the browser: escaping here is
    // what stops a filename becoming markup.
    expect(html).not.toContain('<script>alert(1)</script>');
    expect(html).toContain('&lt;script&gt;');
    expect(html).toContain('&quot;');
    expect(html).toContain('&#39;');
    expect(html).toContain('&amp;');
  });

  it('escapes every character it claims to', () => {
    const html = renderShell({
      'app.js': `&<>"'`,
      'app.css': '/a.css',
      'theme-boot.js': '/t.js',
    } as never);

    // Ampersand first, or the other escapes would be double-escaped.
    expect(html).toContain('&amp;&lt;&gt;&quot;&#39;');
  });
});

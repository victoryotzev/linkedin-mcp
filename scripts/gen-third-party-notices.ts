// Generates THIRD-PARTY-NOTICES.md from package-lock.json.
//
// Why this exists: the MCP server bundle inlines workspace code together with
// some runtime dependencies (yauzl), and the browser bundle inlines hono with
// `legalComments: 'none'`. MIT and BSD require their notice to travel with
// distributed copies, so any release artifact needs this file alongside it.
// pdfjs-dist (Apache-2.0) is NOT bundled — it is imported at runtime inside the
// PDF child process — but it is listed here too, because it ships in the
// dependency tree a user installs.
//
//   npm run notices
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface LockEntry {
  version?: string;
  license?: string | string[];
  resolved?: string;
  dev?: boolean;
  link?: boolean;
}

const root = new URL('../', import.meta.url);
const lock = JSON.parse(
  readFileSync(fileURLToPath(new URL('package-lock.json', root)), 'utf8'),
) as { packages: Record<string, LockEntry> };

interface Entry {
  name: string;
  version: string;
  license: string;
  dev: boolean;
}

const entries: Entry[] = [];
for (const [path, meta] of Object.entries(lock.packages)) {
  // '' is this repo; `link: true` entries are the workspaces, which are covered
  // by LICENSE rather than by a third-party notice.
  if (path === '' || meta.link || !path.startsWith('node_modules/')) continue;
  const license = Array.isArray(meta.license) ? meta.license.join(' OR ') : meta.license;
  entries.push({
    name: path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length),
    version: meta.version ?? 'unknown',
    license: license ?? 'UNKNOWN — check the package',
    dev: meta.dev === true,
  });
}
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const byLicense = new Map<string, Entry[]>();
for (const entry of entries) {
  const bucket = byLicense.get(entry.license) ?? [];
  bucket.push(entry);
  byLicense.set(entry.license, bucket);
}

const lines: string[] = [
  '# Third-party notices',
  '',
  '<!-- Generated by `npm run notices`. Do not edit by hand. -->',
  '',
  'This project bundles or installs the packages below. Each remains under its',
  'own license, held by its own copyright holders. Packages marked **(dev)** are',
  'build- or test-time only and are not part of any shipped artifact.',
  '',
  `Generated from \`package-lock.json\`: ${entries.length} packages, ` +
    `${entries.filter((e) => !e.dev).length} runtime, ${entries.filter((e) => e.dev).length} dev.`,
  '',
];
for (const license of [...byLicense.keys()].sort()) {
  const bucket = byLicense.get(license)!;
  lines.push(`## ${license} (${bucket.length})`, '');
  for (const e of bucket) lines.push(`- \`${e.name}@${e.version}\`${e.dev ? ' **(dev)**' : ''}`);
  lines.push('');
}
lines.push(
  '## Full license texts',
  '',
  'Each package ships its own license file inside `node_modules/<name>/`. Run',
  '`npm ci` and read them there, or fetch them from the package registry entry',
  'recorded in `package-lock.json`.',
  '',
);

writeFileSync(fileURLToPath(new URL('THIRD-PARTY-NOTICES.md', root)), lines.join('\n'), 'utf8');
console.log(
  `wrote THIRD-PARTY-NOTICES.md (${entries.length} packages, ${byLicense.size} licenses)`,
);
